from Graph import *

def build_Italy():
    '''returns a graph where neighbouring regions are joined by an edge'''
    Italy = UndirectedGraph()
    Italy.add_edge("Val d'Aosta", "Piemonte")
    Italy.add_edge("Piemonte", "Liguria")
    Italy.add_edge("Piemonte", "EmiliaRomagna")
    Italy.add_edge("Piemonte", "Lombardia")
    Italy.add_edge("Liguria", "EmiliaRomagna")
    Italy.add_edge("Liguria", "Toscana")
    Italy.add_edge("Lombardia", "Trentino")
    Italy.add_edge("Lombardia", "Veneto")
    Italy.add_edge("Lombardia", "EmiliaRomagna")
    Italy.add_edge("Veneto", "Friuli")
    Italy.add_edge("Veneto", "EmiliaRomagna")
    Italy.add_edge("Veneto", "Trentino")
    Italy.add_edge("EmiliaRomagna", "Toscana")
    Italy.add_edge("EmiliaRomagna", "Marche")
    Italy.add_edge("Toscana", "Marche")
    Italy.add_edge("Toscana", "Umbria")
    Italy.add_edge("Toscana", "Lazio")
    Italy.add_edge("Umbria", "Marche")
    Italy.add_edge("Umbria", "Abruzzo")
    Italy.add_edge("Umbria", "Lazio")
    Italy.add_edge("Marche", "Lazio")
    Italy.add_edge("Lazio", "Abruzzo")
    Italy.add_edge("Lazio", "Molise")
    Italy.add_edge("Lazio", "Campania")
    Italy.add_edge("Abruzzo", "Molise")
    Italy.add_edge("Molise", "Campania")
    Italy.add_edge("Molise", "Puglia")
    Italy.add_edge("Campania", "Puglia")
    Italy.add_edge("Campania", "Basilicata")
    Italy.add_edge("Basilicata", "Puglia")
    Italy.add_edge("Basilicata", "Calabria")
    Italy.add_vertex("Sicilia")
    Italy.add_vertex("Sardegna")
    return(Italy)

Italy = build_Italy()
print(Italy)
print("BFS visit:", Italy.bfs_visit('Lazio'))
print("BFS tree:\n", Italy.bfs_tree("Lazio"))
print("DFS visit:", Italy.dfs_visit('Lazio'))
print("DFS tree:\n", Italy.dfs_tree("Lazio"))
